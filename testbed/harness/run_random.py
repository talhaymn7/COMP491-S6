"""Method R: random (schema-based, change-unaware) rollback testing.

Same V1 -> V2 -> V1 cycle and the same V1 probe as Method B. The only difference:
instead of the fixed hand-written inputs, V2 writes N inputs generated by Hypothesis
from V2's own model definition. Repeated with several seeds because the result is random.

Reported per scenario:
  detection rate over seeds, mean index of the first input that exposed the problem,
  inputs rejected by V2 validation (wasted budget), time.
"""
import json
import statistics

from common import RESULTS, Timer, build_v2, manage, save
from run_fixed import FIXED_INPUTS, rollback_cycle
from suite import SCENARIOS

BUDGET = 20          # generated inputs per run (B uses 3 + 3)
SEEDS = list(range(1, 11))
GLOBAL_STEPS = {"create", "report", "list"}   # failures not tied to one stored order


def generate(scenario, n, seed):
    app_v2 = build_v2(scenario)
    out = RESULTS / "work" / "R_inputs" / f"{scenario['id']}_seed{seed}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    manage(app_v2, "gen_random", "--n", str(n), "--seed", str(seed), "--out", str(out), db="rbtest", check=True)
    return json.loads(out.read_text(encoding="utf-8"))


def first_detecting_input(probe, written_v2):
    """1-based index among V2-written inputs of the first input whose order has a finding."""
    f = probe["findings"]
    if not f:
        return None
    # Per-order findings identify the culprit input. A failing list endpoint is usually
    # caused by one bad stored order, so it is not treated as data-independent.
    bad_ids = {x["order_id"] for x in f if x["order_id"] is not None}
    for i, w in enumerate(written_v2, start=1):
        if w["id"] in bad_ids:
            return i
    return 1  # only data-independent failures (create/report) or pre-upgrade data


def main():
    rows = []
    for s in SCENARIOS:
        runs = []
        for sd in SEEDS:
            with Timer() as t:
                inputs = generate(s, BUDGET, sd)
                probe, rejected, timings = rollback_cycle(s, FIXED_INPUTS, inputs, f"R{sd}")
            written_v2 = json.loads((RESULTS / "work" / f"R{sd}" / s["id"] / "out_v2.json").read_text(encoding="utf-8"))
            runs.append({
                "seed": sd, "detected": bool(probe["findings"]),
                "first_detecting_input": first_detecting_input(probe, written_v2),
                "finding_steps": sorted({x["step"] for x in probe["findings"]}),
                "rejected_by_v2": len(rejected), "seconds": round(t.seconds, 2),
                "sample_finding": probe["findings"][0] if probe["findings"] else None,
            })
        hits = [r for r in runs if r["detected"]]
        firsts = [r["first_detecting_input"] for r in hits]
        row = {
            "scenario": s["id"], "category": s["category"], "truth": s["rollback_incompatible"],
            "R_detection_rate": len(hits) / len(runs),
            "R_detected": len(hits) / len(runs) >= 0.5,   # majority of seeds
            "mean_first_detecting_input": round(statistics.mean(firsts), 1) if firsts else None,
            "mean_rejected_by_v2": round(statistics.mean(r["rejected_by_v2"] for r in runs), 1),
            "budget": BUDGET, "seeds": len(SEEDS),
            "seconds": round(statistics.mean(r["seconds"] for r in runs), 2),
            "runs": runs,
        }
        rows.append(row)
        print(f"{s['id']:<24} truth={s['rollback_incompatible']!s:<5} detected_in={len(hits)}/{len(runs)} seeds "
              f"first_input~{row['mean_first_detecting_input']} rejected~{row['mean_rejected_by_v2']}/{BUDGET} "
              f"({row['seconds']:.1f}s/run)")
    save("R_random.json", rows)


if __name__ == "__main__":
    main()
